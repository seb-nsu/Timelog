export interface MobileTranslator extends Translator {
  m: (key: MobileKey, params?: Record<string, string | number>) => string;
  absence: (kind: AbsenceKind) => string;
  weekday: (index: number) => string;
  reminder: (kind: ReminderKind) => { title: string; body: string };
  /** BCP-47 für Intl */
  tag: string;
}

export function createMobileTranslator(locale: Locale): MobileTranslator {
  const base = createTranslator(locale);
  const messages: Record<MobileKey, string> = locale === 'en' ? en : de;
  const m: MobileTranslator['m'] = (key, params) =>
    messages[key].replace(/\{(\w+)\}/g, (match, name: string) =>
      params && name in params ? String(params[name]) : match,
    );
  return {
    ...base,
    m,
    absence: (kind) => ABSENCE_LABELS[locale][kind],
    weekday: (index) => WEEKDAYS[locale][index] ?? '',
    reminder: (kind) => ({ title: m(`notify.${kind}.title`), body: m(`notify.${kind}.body`) }),
    tag: locale === 'en' ? 'en-GB' : 'de-DE',
  };
}

